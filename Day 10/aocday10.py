import re

def parse_button_list(lst):
    result = []
    for button in lst:
        nums = re.findall(r"\d+", button)
        nums = list(map(int, nums))
        result.append(nums)
    return result

def parse_voltage(s):
    nums = re.findall(r"\d+", s)
    return list(map(int, nums))

def pad_lists(data, size):
    padded = []
    for lst in data:
        returnList = []
        for i in range(size):
          if i in lst:
            returnList.append(1)
          else:
            returnList.append(0)
        padded.append(returnList)
    return padded

def pad_buttons(voltage, buttonList):
  return pad_lists(buttonList, len(voltage))

