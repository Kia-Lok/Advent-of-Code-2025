from collections import deque

def min_presses(target_bits, button_bits):
    q = deque([(0, 0)])
    memo = {0: 0}

    while q:
        state, presses = q.popleft()
        if state == target_bits:
            return presses

        for b in button_bits:
            new_state = state ^ b
            new_cost = presses + 1

            if new_state not in memo or new_cost < memo[new_state]:
                memo[new_state] = new_cost
                q.append((new_state, new_cost))

    return None

def parse_indicator(formation_str):
    inside = formation_str.strip()[1:-1]
    bitmask = 0
    for i, ch in enumerate(inside):
        if ch == '#':
            bitmask |= (1 << i)
    return bitmask

def parse_button(button_str):
    inner = button_str.strip()[1:-1]
    if not inner:
        return 0
    indices = map(int, inner.split(','))
    bitmask = 0
    for i in indices:
        bitmask |= (1 << i)
    return bitmask

